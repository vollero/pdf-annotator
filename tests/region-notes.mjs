import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PDFDocument } from 'pdf-lib'

export async function checkRegionNotes(page, downloadAnnotations, importAnnotations) {
  const pdf = await PDFDocument.create()
  pdf.addPage([500,360]).drawText('Sample',{x:170,y:200,size:16})
  const original = Buffer.from(await pdf.save())
  async function open(name,buffer) {
    await page.locator('#file').setInputFiles({name,mimeType:'application/pdf',buffer})
    await page.locator('#filename').filter({hasText:name}).waitFor()
  }
  const snapshot = async()=>JSON.parse((await downloadAnnotations(page)).buffer)
  async function drag(x,y,dx,dy,cancel=false) {
    await page.mouse.move(x,y)
    await page.mouse.down()
    await page.mouse.move(x+dx,y+dy,{steps:5})
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
  }
  await open('Survey table.pdf',original)
  const paper = page.locator('.paper.current[data-ready="true"]')
  const textBox = await paper.getByText('Sample',{exact:true}).boundingBox()
  const cx = textBox.x+textBox.width/2, cy = textBox.y+textBox.height/2
  await page.getByRole('button',{name:'Region',exact:true}).click()
  const editor = page.locator('#note-dialog')
  const region = paper.locator('.region-note')
  await page.mouse.click(cx,cy)
  await editor.getByRole('heading',{name:'Add a region note'}).waitFor()
  await editor.getByRole('button',{name:'Cancel'}).click()
  await drag(cx+75,cy+35,-150,-70,true)
  assert.ok(await editor.isHidden())
  assert.equal(await region.count(),0)
  await drag(cx+75,cy+35,-150,-70)
  const text = 'Verify the table units.'
  await editor.locator('#note-text').fill(text)
  await editor.getByLabel('Track as action').check()
  await editor.getByRole('button',{name:'Save note'}).click()
  const card = page.locator('.card').filter({hasText:text})
  await card.getByText('Region note',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Select',exact:true}).click()
  await page.mouse.dblclick(cx,cy)
  assert.equal(await page.evaluate(()=>getSelection().toString().trim()),'Sample')
  assert.ok(await editor.isHidden())
  const bounds = await paper.boundingBox()
  const first = (await snapshot()).annotations[0]
  assert.equal(first.type,'region')
  assert.equal(first.done,false)
  assert.ok(Math.abs(first.size[0]*bounds.width-150)<2)
  assert.ok(Math.abs(first.size[1]*bounds.height-70)<2)
  const edge = region.locator('.region-edge')
  const edgeBox = await edge.boundingBox()
  const ex = edgeBox.x+edgeBox.width/2, ey = edgeBox.y
  await page.mouse.click(ex,ey)
  await editor.getByRole('heading',{name:'Edit region note'}).waitFor()
  assert.equal(await editor.locator('#note-text').inputValue(),text)
  await editor.getByRole('button',{name:'Cancel'}).click()
  await drag(ex,ey,35,22,true)
  assert.deepEqual((await snapshot()).annotations,[first])
  await drag(ex,ey,35,22)
  const moved = (await snapshot()).annotations[0]
  assert.deepEqual(moved.size,first.size)
  assert.ok(Math.abs((moved.point[0]-first.point[0])*bounds.width-35)<2)
  const grip = await region.locator('.note-resize-handle').boundingBox()
  await drag(grip.x+grip.width*.7,grip.y+grip.height*.7,30,18)
  const resized = (await snapshot()).annotations[0]
  assert.deepEqual(resized.point,moved.point)
  assert.ok(resized.size.every((v,i)=>v>moved.size[i]))
  await page.locator('#undo').click()
  assert.deepEqual((await snapshot()).annotations,[moved])
  await page.locator('#redo').click()
  await page.locator('#zoom-in').click()
  await region.focus()
  await page.keyboard.press('Shift+ArrowRight')
  const transfer = await downloadAnnotations(page)
  const expected = JSON.parse(transfer.buffer)
  assert.equal(expected.version,6)
  assert.ok(Math.abs(expected.annotations[0].size[0]-resized.size[0]-12/500)<.00001)
  await page.locator('#save-state').getByText('Saved locally',{exact:true}).waitFor()
  await page.reload()
  await region.waitFor()
  assert.deepEqual(await snapshot(),expected)
  await card.locator('.more').click()
  await card.getByRole('button',{name:'Delete'}).click()
  assert.equal(await region.count(),0)
  await importAnnotations(page,transfer,'1 added, 0 updated')
  assert.deepEqual(await snapshot(),expected)
  const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#export').click()])
  await open('Survey table annotated.pdf',await readFile(await download.path()))
  await region.waitFor()
  assert.deepEqual((await snapshot()).annotations,expected.annotations)
}
