import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { PDFDocument } from 'pdf-lib'

export async function checkPinnedPreview(page,downloadAnnotations,importAnnotations) {
  const pdf = await PDFDocument.create()
  pdf.addPage([500,600])
  pdf.addPage([400,500])
  const bytes = Buffer.from(await pdf.save())
  const task = {id:'task',type:'note',page:1,text:'Check the scale.',done:false,color:'#a34b26',point:[.2,.2]}
  const region = {id:'figure',type:'region',page:2,text:'Correct the legend.',color:'#266182',point:[.1,.35],size:[.2,.17]}
  const comment = {id:'quote',type:'comment',page:1,text:'Compare the two measurements.',color:'#aa8822',
    passages:[1,2].map(page=>({page,quote:'Measurement',rects:[[.2,.6,.3,.03]]}))}
  const expanded = {...task,id:'expanded',point:[.3,.43],size:[.25,.12],text:'Read the table. '.repeat(100)}
  const transfer = {format:'margin-annotations',version:6,documentSha256:createHash('sha256').update(bytes).digest('hex'),
    annotations:[task,region,comment,expanded]}
  const card = id=>page.locator('.card').filter({has:page.locator('.card-body[data-id="'+id+'"]')})
  const marker = id=>page.locator('.paper.current .note-marker[data-id="'+id+'"]')
  const menu = async (id,name)=>{
    await card(id).locator('.more').click()
    await card(id).getByRole('button',{name,exact:true}).click()
  }
  const open = async(name,buffer)=>{
    await page.locator('#file').setInputFiles({name,mimeType:'application/pdf',buffer})
    await page.locator('#filename').filter({hasText:name}).waitFor()
  }
  const saved = ()=>page.locator('#save-state').getByText('Saved locally',{exact:true}).waitFor()
  const pinned = page.getByRole('group',{name:'Pinned note preview',exact:true})
  const text = pinned.getByRole('note')
  await open('Scale notes.pdf',bytes)
  await importAnnotations(page,{name:'Scale.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(transfer))},'4 added, 0 updated')
  await saved()
  await page.reload()
  await page.locator('#page-layout').selectOption('single')
  await marker(task.id).hover()
  await page.getByRole('group',{name:'Note preview',exact:true}).getByRole('button',{name:'Pin preview'}).click()
  await pinned.waitFor()
  assert.equal(await text.textContent(),'To do · '+task.text)
  assert.equal(await pinned.locator('#preview-source').textContent(),'Note · Page 1')
  assert.ok(await page.locator('#undo').isDisabled())
  assert.deepEqual(JSON.parse((await downloadAnnotations(page)).buffer),transfer)
  const corner = await pinned.boundingBox()
  await page.locator('#zoom-in').click()
  await page.locator('#next').click()
  await marker(comment.id).hover()
  assert.deepEqual(await pinned.boundingBox(),corner)
  assert.equal(await text.textContent(),'To do · '+task.text)
  await page.locator('#page-layout').selectOption('continuous')
  await page.locator('#scroller').evaluate(el=>el.scrollTo(0,0))
  await page.locator('.paper.current[data-page="1"][data-ready="true"]').waitFor()
  assert.equal(await text.textContent(),'To do · '+task.text)
  await page.locator('#workspace-toggle').click()
  assert.ok(await pinned.isVisible())
  await page.locator('#workspace-toggle').click()
  const other = await page.context().newPage()
  try {
    await other.goto(page.url())
    const otherCard = other.locator('.card').filter({hasText:task.text})
    await otherCard.getByRole('checkbox').check()
    await text.filter({hasText:'Done · '+task.text}).waitFor()
  } finally { await other.close() }
  await menu(task.id,'Edit note')
  await page.keyboard.press('Escape')
  assert.ok(await pinned.isVisible(),'Escape in the editor dismisses its dialog first')
  await menu(task.id,'Edit note')
  await page.locator('#note-text').fill('Scale verified.')
  await page.locator('#note-save').click()
  assert.equal(await text.textContent(),'Done · Scale verified.')
  await menu(task.id,'Convert to region note')
  await pinned.getByText('Region note · Page 1',{exact:true}).waitFor()
  await menu(expanded.id,'Pin preview')
  assert.equal(await text.textContent(),'To do · '+expanded.text)
  assert.ok(await text.evaluate(el=>el.scrollHeight>el.clientHeight))
  await text.evaluate(el=>{el.scrollTop=el.scrollHeight})
  await page.locator('#workspace-toggle').click()
  await page.setViewportSize({width:400,height:600})
  const narrow = await pinned.boundingBox()
  assert.ok(narrow.x>=0 && narrow.x+narrow.width<=400)
  assert.ok(await pinned.getByRole('button',{name:'Unpin preview'}).isVisible())
  await page.setViewportSize({width:1360,height:920})
  await page.locator('#workspace-toggle').click()
  await menu(expanded.id,'Unpin preview')
  assert.ok(await pinned.isHidden())

  await marker(comment.id).focus()
  await page.keyboard.press('p')
  assert.equal(await pinned.locator('#preview-source').textContent(),'Passage comment · Pages 1–2')
  await page.keyboard.press('p')
  assert.ok(await pinned.isHidden())
  await menu(region.id,'Pin preview')
  await menu(region.id,'Delete')
  assert.ok(await pinned.isHidden())
  await page.locator('#undo').click()
  assert.ok(await pinned.isHidden())
  await menu(region.id,'Pin preview')
  await page.locator('#scroller').focus()
  await page.keyboard.press('Escape')
  assert.ok(await pinned.isHidden())
  await menu(task.id,'Pin preview')
  await pinned.getByRole('button',{name:'Unpin preview'}).click()
  assert.ok(await pinned.isHidden())
  await menu(task.id,'Pin preview')
  await saved()
  await page.reload()
  await card(task.id).waitFor()
  assert.ok(await pinned.isHidden())
  await menu(task.id,'Pin preview')
  const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#export').click()])
  await open('Scale notes annotated.pdf',await readFile(await download.path()))
  await card(task.id).waitFor()
  assert.ok(await pinned.isHidden(),'Opening a PDF with the same annotation IDs clears the pin')
  await page.locator('#page-layout').selectOption('single')
}
