import assert from 'node:assert/strict'

export async function checkAnnotationSearch(page) {
  const search = page.getByRole('searchbox', {name:'Search annotations'})
  const scope = page.getByRole('combobox', {name:'Filter annotations by page'})
  const status = page.getByRole('combobox', {name:'Filter by action status'})
  const summary = page.locator('#search-summary')
  const cards = page.locator('.card')

  await search.fill('  PROFILE   ridge  ')
  assert.equal(await cards.count(),1)
  assert.match(await cards.textContent(),/Compare the ridge/)
  await search.fill('FoRcEs shaped')
  assert.match(await cards.textContent(),/Every ridge holds/)
  await search.fill('2')
  assert.equal(await cards.count(),2,'A bare number finds the page and a note mentioning it')
  await search.fill('page 2')
  assert.equal(await cards.count(),1,'An explicit page excludes mentions on other pages')
  await search.fill('page 2   SHADOW')
  const result = cards.getByRole('button',{name:/Trace the crest/})
  await result.focus()
  await page.keyboard.press('Enter')
  await page.locator('.paper.current[data-page="2"][data-ready="true"]').waitFor()
  assert.match(await page.locator('.card.selected .card-body').textContent(),/Trace the crest/)
  assert.ok(await result.evaluate(el => el === document.activeElement))

  await scope.selectOption('current')
  await search.fill('reviewed 注釈')
  assert.equal(await summary.textContent(),'0 matching annotations')
  await page.getByRole('button',{name:'Previous page'}).click()
  await page.locator('.paper.current[data-page="1"][data-ready="true"]').waitFor()
  await status.selectOption('todo')
  assert.equal(await cards.count(),0)
  await status.selectOption('done')
  assert.equal(await summary.textContent(),'1 matching annotation')
  assert.ok(await cards.getByRole('checkbox').isChecked())
  await cards.getByRole('checkbox').click()
  assert.equal(await summary.textContent(),'0 matching annotations')
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  assert.equal(await summary.textContent(),'1 matching annotation')
  await search.fill('ridge')
  assert.equal(await status.locator('option[value="done"]').textContent(),'Done (0)')
  await search.press('Escape')
  assert.equal(await search.inputValue(),'')
  assert.equal(await summary.textContent(),'')
  assert.equal(await cards.count(),1,'Clearing the search retains the selected action filter')
  await status.selectOption('all')
  await scope.selectOption('all')
  assert.equal(await cards.count(),6)
}
