import assert from 'node:assert/strict'

export async function checkNoteAppearance(page) {
  const sidebar = page.locator('#annotations-panel')
  const card = sidebar.locator('.card').filter({hasText:'Compare the ridge'}).locator('.card-body')
  const marker = page.locator('.paper.current .note-marker').first()
  const tooltip = page.getByRole('tooltip')
  const editor = page.locator('#note-dialog')
  const textarea = editor.getByRole('textbox',{name:'Note',exact:true})
  const settings = page.getByRole('dialog',{name:'Note appearance'})
  const appearanceButton = {name:'Note appearance',exact:true}
  const fontOf = locator => locator.evaluate(el => {
    const {fontSize,fontFamily} = getComputedStyle(el)
    return [fontSize,fontFamily]
  })

  const original = await card.textContent()
  assert.equal((await fontOf(card))[0],'18px')
  const initialPanel = await sidebar.boundingBox()
  await marker.hover()
  await tooltip.waitFor()
  assert.equal(await tooltip.textContent(),original)
  assert.deepEqual(await fontOf(tooltip),await fontOf(card))
  await page.keyboard.press('Escape')
  assert.ok(await tooltip.isHidden())
  await marker.focus()
  await page.keyboard.press('Enter')
  await editor.waitFor()
  assert.equal(await textarea.inputValue(),original)
  assert.deepEqual(await fontOf(textarea),await fontOf(card))
  const initialBox = await editor.boundingBox()
  const initialText = await textarea.boundingBox()
  const draft = original + ' Add a second observation.'
  await textarea.fill(draft)
  await editor.getByRole('button',appearanceButton).click()
  assert.equal(await settings.locator('#appearance-example').textContent(),draft)
  await settings.getByLabel('Font',{exact:true}).selectOption('serif')
  await settings.getByLabel('Text size').selectOption('24')
  await settings.getByLabel('Box size').selectOption('spacious')
  if (process.env.MARGIN_NOTE_PREVIEW_PATH) {
    await settings.screenshot({path:process.env.MARGIN_NOTE_PREVIEW_PATH,animations:'disabled'})
  }
  await settings.getByRole('button',{name:'Done'}).click()
  assert.equal(await textarea.inputValue(),draft)
  assert.ok((await editor.boundingBox()).width > initialBox.width)
  assert.ok((await textarea.boundingBox()).height > initialText.height)
  assert.ok((await sidebar.boundingBox()).width > initialPanel.width)
  await editor.getByRole('button',{name:'Cancel'}).click()
  assert.equal(await card.textContent(),original)
  assert.equal((await fontOf(card))[0],'24px')
  assert.match((await fontOf(card))[1], /Georgia/)
  await page.reload()
  await page.locator('.paper.current[data-ready="true"]').waitFor()
  await marker.focus()
  await tooltip.waitFor()
  assert.deepEqual(await fontOf(tooltip),await fontOf(card))
  assert.equal((await fontOf(tooltip))[0],'24px')
  assert.match((await fontOf(tooltip))[1],/Georgia/)
  await page.keyboard.press('Escape')

  await page.setViewportSize({width:360,height:510})
  await sidebar.getByRole('button',appearanceButton).click()
  await settings.getByLabel('Font',{exact:true}).selectOption('mono')
  await settings.getByLabel('Text size').selectOption('32')
  for (const el of [settings, sidebar, settings.locator('#appearance-example')]) {
    const bounds = await el.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 360,'Reading box ' + await el.getAttribute('id') + ' exceeds 360 px: ' + JSON.stringify(bounds))
    assert.ok(await el.evaluate(node => node.scrollWidth <= node.clientWidth),'Text wraps inside the box')
  }
  assert.match((await fontOf(card))[1],/monospace/)
  await settings.getByLabel('Box size').selectOption('compact')
  await settings.getByRole('button',{name:'Done'}).click()
  assert.ok((await sidebar.boundingBox()).width < initialPanel.width)
  await sidebar.getByRole('button',appearanceButton).click()
  await settings.getByRole('button',{name:'Restore defaults'}).click()
  assert.equal(await settings.getByLabel('Font',{exact:true}).inputValue(),'sans')
  assert.equal(await settings.getByLabel('Text size').inputValue(),'18')
  assert.equal(await settings.getByLabel('Box size').inputValue(),'comfortable')
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:1360,height:920})
  await page.waitForFunction(() => {
    const paper = document.querySelector('.paper.current[data-ready="true"]')
    const text = paper?.querySelector('.textLayer')
    const scale = Number(text?.style.getPropertyValue('--total-scale-factor'))
    const pageWidth = parseFloat(paper?.style.getPropertyValue('--page-width'))
    return text && Math.abs(pageWidth * scale - paper.getBoundingClientRect().width) < 1
  })
  assert.deepEqual(await fontOf(card),['18px','system-ui, sans-serif'])
}
