import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { PDFDocument } from 'pdf-lib'

export async function checkPassageComments(page, downloadAnnotations, importAnnotations) {
  const pdf = await PDFDocument.create()
  const lines = ['The first measurement','continues on this page.']
  for (const line of lines) pdf.addPage([400,160]).drawText(line,{x:24,y:100,size:15})
  await page.locator('#file').setInputFiles({name:'Measurements.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())})
  await page.locator('#filename').filter({hasText:'Measurements.pdf'}).waitFor()
  await page.locator('#page-layout').selectOption('continuous')
  const first = page.locator('.paper .textLayer span').filter({hasText:lines[0]}).first()
  await first.waitFor()
  const box = await first.boundingBox()
  await page.mouse.move(box.x+1,box.y+box.height/2)
  await page.mouse.down()
  await page.mouse.move(box.x+box.width-1,box.y+box.height/2,{steps:8})
  await page.mouse.up()
  const actions = page.getByRole('group',{name:'Selected passage'})
  await actions.getByRole('button',{name:'Comment',exact:true}).click()
  const editor = page.getByRole('dialog',{name:'Comment on passage'})
  assert.match(await editor.locator('blockquote').textContent(),/first measurement/)
  await editor.getByRole('button',{name:'Cancel'}).click()
  assert.equal(await page.locator('.card').count(),0)

  await page.locator('.paper[data-page="2"][data-ready="true"]').waitFor()
  await page.evaluate(lines => {
    const [a,b] = lines.map(s => [...document.querySelectorAll('.paper .textLayer span')].find(el=>el.textContent===s).firstChild)
    const selection = getSelection()
    selection.setBaseAndExtent(b,b.length,a,0)
  },lines)
  await actions.waitFor()
  await page.keyboard.press('c')
  const quote = await editor.locator('blockquote').textContent()
  assert.equal(quote.trim().replace(/\s+/g,' '),lines.join(' '))
  await editor.getByRole('textbox',{name:'Comment'}).fill('Verify both units.')
  await editor.getByLabel('Track as action').check()
  await editor.getByRole('button',{name:'Save comment'}).click()
  const card = page.locator('.card')
  assert.equal(await card.count(),1)
  assert.equal(await card.locator('.card-quote').textContent(),quote)
  assert.ok(await card.getByRole('checkbox').isVisible())
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  assert.equal(await card.count(),0)
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  const search = page.getByRole('searchbox')
  await search.fill('page 2 measurement units')
  assert.equal(await card.count(),1)
  assert.equal(await card.locator('.card-body').getAttribute('title'),'Show on page 2')
  await card.locator('.card-body').click()
  const marker = page.locator('.paper[data-page="2"] .note-marker')
  await marker.focus()
  await page.keyboard.press('Enter')
  assert.equal(await editor.locator('blockquote').textContent(),quote)
  await editor.getByRole('textbox',{name:'Comment',exact:true}).fill('Units verified.')
  await editor.getByLabel('Done',{exact:true}).check()
  await editor.getByRole('button',{name:'Save comment'}).click()
  const migration = await downloadAnnotations(page)
  const data = JSON.parse(migration.buffer)
  assert.equal(data.version,3)
  assert.equal(data.annotations.length,1)
  const [comment] = data.annotations
  assert.deepEqual(comment.passages.map(p=>p.page),[1,2])
  assert.equal(comment.passages.map(p=>p.quote).join('\n'),quote)
  assert.equal(comment.text,'Units verified.')
  assert.equal(comment.done,true)
  await card.locator('.more').click()
  await card.getByRole('button',{name:'Delete'}).click()
  await importAnnotations(page,migration,'1 added, 0 updated')
  await page.locator('#save-state').getByText('Saved locally',{exact:true}).waitFor()
  await page.reload()
  await card.waitFor()
  assert.ok(await card.getByRole('checkbox').isChecked())
  const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#export').click()])
  const exported = await readFile(await download.path())
  await page.locator('#file').setInputFiles({name:'Reviewed measurements.pdf',mimeType:'application/pdf',buffer:exported})
  await page.locator('#filename').filter({hasText:'Reviewed measurements.pdf'}).waitFor()
  assert.deepEqual(JSON.parse((await downloadAnnotations(page)).buffer).annotations,[comment])
  await page.locator('#page-layout').selectOption('single')
}
